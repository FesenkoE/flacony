{
    public function run(): void
    {
        $user = fn (string $email, string $name) => User::firstOrCreate(
            ['email' => $email],
            User::factory()->raw(['name' => $name, 'email' => $email]),
        );

        $test = $user('test@example.com', 'Test User');
        $anna = $user('anna.seller@example.com', 'Анна Литвин');
        $igor = $user('igor.seller@example.com', 'Игорь Ковальчук');
        $marina = $user('marina.seller@example.com', 'Марина Дорош');
        $dmitry = $user('dmitry.seller@example.com', 'Дмитрий Панов');
        $oleg = $user('oleg@example.com', 'Олег Мельник');
        $kateryna = $user('kateryna@example.com', 'Катерина Бондар');
        $sergey = $user('sergey@example.com', 'Сергей Ткач');

        $categories = collect([
            ['name' => 'Общие обсуждения', 'description' => 'Всё, что не подошло под другие разделы'],
            ['name' => 'Вопросы новичков', 'description' => 'Только начинаешь разбираться в парфюмерии — сюда'],
            ['name' => 'Отзывы о продавцах', 'description' => 'Делимся опытом покупок на витринах'],
        ])->map(fn (array $entry) => ForumCategory::firstOrCreate(['slug' => str($entry['name'])->slug()], $entry));

        // category index · days since opened · author · opening message · replies (one every few hours)
        $topics = [
            [1, 20, 'С чего начать, если раньше пользовался только масс-маркетом?', $test,
                'Пользовался только масс-маркетом, хочу попробовать нишу, но брать флакон вслепую за несколько тысяч страшно. С чего посоветуете начать?', [
                    [$anna, 'Начни с распива — возьми 2-3 мл разных ароматов из разных семейств (древесные, цитрусовые, амбровые), чтобы понять, что вообще нравится, прежде чем брать полный флакон.'],
                    [$igor, 'Согласен с советом выше. Ещё добавлю: не нюхай больше 3 ароматов подряд за раз, нос "устаёт" и перестаёт различать оттенки.'],
                ]],
            [0, 17, 'Как отличить оригинал от подделки при покупке распива?', $marina,
                'Хочу взять распив Aventus у незнакомого продавца и боюсь нарваться на подделку. На что смотреть до покупки и как проверить уже после?', [
                    [$dmitry, 'Смотри на батч-код флакона, откуда наливают — большинство брендов дают проверить его на официальном сайте. Плюс сравнивай цвет и вязкость с фото оригинала.'],
                ]],
            [2, 15, 'Отзыв о покупке у Игоря — Aventus пришёл быстро и герметично упакован', $test,
                'Брал у Игоря 5 мл Aventus: отправил на следующий день, дошло за два дня, атомайзер стеклянный, ничего не протекло. По ощущениям один в один с флаконом из магазина.', [
                    [$igor, 'Спасибо за отзыв! Всегда упаковываю в стекло с уплотнителем, чтобы точно не протекло при доставке.'],
                ]],
            [1, 12, 'Чем отличается EDT от EDP и стоит ли переплачивать?', $oleg,
                'Вижу один и тот же аромат в EDT и EDP с разницей в цене почти в полтора раза. Это просто крепость или они реально по-разному пахнут?', [
                    [$anna, 'Не только крепость. Часто это разные композиции под одним названием — у Sauvage, например, EDP заметно теплее и с ванилью. Лучше взять распив обоих и сравнить на коже.'],
                    [$kateryna, 'Плюс EDP обычно дольше держится, но не всегда громче. Мне EDT иногда даже больше нравятся — свежее.'],
                ]],
            [0, 10, 'Мацерація — міф чи реально працює?', $dmitry,
                'Часто читаю, що після відкриття флакона аромат «дозріває» через кілька тижнів. У когось реально змінювався запах, чи це самонавіювання?', [
                    [$igor, 'На Aventus помітив різницю: перші тижні було більше спирту на старті, потім стало м\'якше. Але це скоріше про перші хвилини, суть аромату та сама.'],
                    [$sergey, 'Думаю, частково самонавіювання — ніс звикає до аромату, і здається, що він змінився.'],
                ]],
            [1, 8, 'Як зрозуміти, чи підходить аромат, якщо в магазині все пахне однаково?', $kateryna,
                'Після п\'ятого блотера в магазині вже не розрізняю, що подобається, а що ні. Як ви обираєте?', [
                    [$marina, 'Блотер — тільки щоб відсіяти. Те, що сподобалось, наносьте на шкіру і ходіть хоча б пару годин: база розкривається пізніше, і саме її ви будете чути весь день.'],
                    [$oleg, 'Я для цього і беру розпив — дома спокійно носиш кілька днів і вже точно розумієш.'],
                ]],
            [2, 6, 'Марина — Layton пришёл аккуратно, с подписанным атомайзером', $oleg,
                'Брал у Марины 5 мл Layton. Атомайзер подписан (название, объём, дата распива), батч-код флакона прислала фото в переписке, не просил. Приятно.', [
                    [$marina, 'Спасибо, Олег! Подписываю всегда — через пару месяцев сам не вспомнишь, что в каком флаконе.'],
                ]],
            [0, 4, 'Как хранить распивы, чтобы не выдохлись?', $kateryna,
                'Набрала уже штук 15 атомайзеров. Где их лучше держать и сколько они вообще живут?', [
                    [$marina, 'Главное — темнота и стабильная температура: закрытая коробка в шкафу, не ванная и не подоконник. В стеклянных атомайзерах год-два спокойно живут.'],
                    [$anna, 'И не держите полупустые долго — чем больше воздуха в атомайзере, тем быстрее окисляются верхние ноты.'],
                ]],
            [1, 3, 'Сколько мл брать на пробу — 2 или 5?', $sergey,
                'Хочу попробовать несколько ароматов Kilian и Mancera. Хватит 2 мл, чтобы понять, или сразу брать 5?', [
                    [$dmitry, '2 мл — это примерно 20–25 пшиков, на неделю ношения хватит, чтобы понять. 5 мл имеет смысл брать, если аромат уже нравится и хочется носить его сезон.'],
                    [$igor, 'Для Angels\' Share я бы сразу 5 — он зимний, а 2 мл закончатся раньше, чем поймёшь, как он раскрывается в холод.'],
                ]],
            [0, 2, 'Ароматы на осень: что носите сейчас?', $anna,
                'Похолодало — достала Naxos и Angels\' Share. Кто что носит этой осенью?', [
                    [$sergey, 'Tobacco Vanille по вечерам, днём Bleu de Chanel — он универсальный.'],
                    [$kateryna, 'Jazz Club від Margiela — затишний, як плед.'],
                    [$test, 'Hacivat на работу, пока ещё не совсем холодно.'],
                ]],
            [2, 1, 'Анна Литвин — відповідає швидко, відправила в день замовлення', $kateryna,
                'Замовила 3 мл Bleu de Chanel у суботу вранці, того ж дня отримала ТТН. Упаковка — пупирка і коробочка, все ціле.', [
                    [$anna, 'Дякую, Катерино! Рада, що сподобалось 🙂'],
                ]],
        ];

        foreach ($topics as [$category, $daysAgo, $title, $author, $opening, $replies]) {
            $opened = now()->subDays($daysAgo)->setTime(10 + $daysAgo % 9, 15);
            $topic = $categories[$category]->topics()->firstOrCreate(
                ['title' => $title],
                ['user_id' => $author->id, 'slug' => str($title)->slug().'-'.str()->random(6)],
            );

            if (! $topic->wasRecentlyCreated) {
                continue;
            }

            $topic->forceFill(['created_at' => $opened, 'updated_at' => $opened])->save();

            // Like a topic created on the site, its opening message is the first reply.
            foreach ([[$author, $opening], ...$replies] as $i => [$replyAuthor, $body]) {
                $at = $opened->copy()->addHours($i * 3);
                $topic->replies()->create(['user_id' => $replyAuthor->id, 'body' => $body])
                    ->forceFill(['created_at' => $at, 'updated_at' => $at])->save();
            }
        }
    }
}
